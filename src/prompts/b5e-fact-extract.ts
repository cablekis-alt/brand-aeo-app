import type { FactGraphNode, PromptMessage } from './types';

/**
 * 브랜드 페이지 → 팩트 그래프 후보.
 *
 * 뽑는 것은 **가게가 스스로 공개한 확인 가능한 값**이다. 마케팅 형용사가 아니다.
 * 둘의 차이가 이 기능의 전부다:
 *
 *   운영 규정  체크인 15:00, 추가 요금 1인 20,000원, 직화구이 금지, 당일 취소 100%
 *             → 가게가 손님과 맺는 약속이라 틀리면 분쟁이 난다. 그래서 정확하다.
 *   마케팅 문구 "최고의 시설", "40여 종 최신 장비", "365일 철저한 소독"
 *             → 언제 쓴 말인지, 지금도 맞는지 아무도 보증하지 않는다.
 *
 * 앞의 것만 가져온다. 뒤의 것은 브리프가 "확인 필요"로 남기는 편이 정직하다.
 */
export const FACT_TYPES_FOR_EXTRACT: readonly FactGraphNode['type'][] = [
  'price',
  'spec',
  'date',
  'certification',
  'location',
  'other',
];

export function buildFactExtractPrompt(brandName: string, industry: string, pageText: string): PromptMessage {
  const system = `당신은 브랜드 페이지에서 **확인 가능한 사실**만 뽑아내는 추출기입니다.

뽑을 것 — 가게가 스스로 공개한, 숫자나 규정으로 확인되는 값:
- 가격·요금 (1박 요금, 추가 인원 요금, 시술 비용)
- 운영 규정 (체크인/체크아웃 시각, 영업시간, 취소·환불 규정, 금지 사항)
- 사양·구성 (객실 수, 인원 기준, 병상 수, 의료진 수, 보유 장비명)
- 위치 (주소, 특정 지점까지의 거리)
- 인증·자격 (보유 인증명, 등록번호, 면허)
- 날짜 (설립·개원·리모델링 연도)

절대 뽑지 말 것:
- 형용사와 홍보 문구 — "최고", "최신", "철저한", "믿을 수 있는", "프리미엄"
- 근거 없이 뭉뚱그린 수량 표현이 **그 자체로 주장인 경우**는 그대로 옮긴다.
  예: 페이지에 "40여 종"이라고 적혀 있으면 value도 정확히 "40여 종"이다. "40종"으로 바꾸지 마라.
- 페이지에 없는 내용 — 업계 상식, 일반적인 안내, 당신이 아는 지식

★ 가장 중요한 규칙:
value는 페이지 본문에 **글자 그대로 있는 문자열**이어야 합니다. 다듬거나, 반올림하거나,
단위를 바꾸거나, 줄여 쓰지 마세요. 그대로 복사하세요. 원문에 "약 20만원"이면 "약 20만원"입니다.
claim은 그 값이 무엇인지 짧은 한국어 명사구로 씁니다(예: "체크인 시각", "추가 인원 요금").

★ 두 번째 규칙 — value는 **문장이 아니라 구(句)**입니다.
value는 나중에 문장 안에 그대로 박힙니다. 문장을 넣으면 겹말이 됩니다.
  원문: "건물과 객실 안은 절대 금연입니다."
    맞음  { "claim": "금연 규정", "value": "절대 금연" }
    틀림  { "claim": "금연 규정", "value": "건물과 객실 안은 절대 금연입니다." }
  원문: "입실 당일 취소와 노쇼는 숙박요금의 100%가 부과됩니다."
    맞음  { "claim": "당일 취소·노쇼 위약금", "value": "숙박요금의 100%" }
    틀림  { "claim": "취소 규정", "value": "입실 당일 취소와 노쇼는 숙박요금의 100%가 부과됩니다." }
종결어미(~입니다·~합니다·~하세요)나 마침표가 붙으면 틀린 것입니다. 40자를 넘겨도 틀린
것입니다. 구로 줄일 수 없는 내용이면 **아예 넣지 마세요** — 억지로 자르지 말고 버리세요.
단, 줄이더라도 남는 글자는 원문에 그대로 있어야 합니다(원문 "절대 금연" → "금연 불가" 안 됨).

출력은 JSON 배열만. 설명·마크다운 금지.
[{ "type": "price"|"spec"|"date"|"certification"|"location"|"other", "claim": string, "value": string }]
최대 20개. 확실하지 않으면 넣지 마세요 — 적게 넣는 편이 낫습니다.`;

  const user = `브랜드: ${brandName}${industry ? ` (${industry})` : ''}

페이지 본문:
"""
${pageText}
"""`;
  return { system, user };
}
